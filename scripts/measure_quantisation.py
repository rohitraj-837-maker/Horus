"""Measure the vertical-rate step size empirically and write it to data_notes.

uv run python scripts/measure_quantisation.py --day 2026-11-15 [--source opensky]
"""

from __future__ import annotations

import argparse
import sys
from datetime import date

from turbcast.ingest import quantisation, store
from turbcast.reports import replace_section


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--day", type=date.fromisoformat, required=True)
    ap.add_argument("--source", default="opensky", choices=sorted(store.SOURCES))
    args = ap.parse_args()

    df = store.load_day(args.day, args.source, columns=["icao24", "time", "vr_fpm", "msg_type"])
    if df.empty:
        print(f"no {args.source} data for {args.day}", file=sys.stderr)
        return 1
    table = quantisation.summarise(df)
    print(table.to_string(index=False))
    body = (
        f"Source `{args.source}`, day {args.day} (UTC), {len(df):,} rows. "
        f"Generated by `scripts/measure_quantisation.py`.\n\n"
        + table.to_markdown(index=False, floatfmt=".3f")
    )
    replace_section("data_notes.md", f"quantisation-{args.source}", body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
