"""Performance bench (SPEC §6.4, M5): one live grid update for N aircraft.

    uv run python -m horus.eval.perf_bench [--aircraft 10000] [--reps 50]

A synthetic snapshot of N aircraft positions over the region at FL200-FL450, with
turbulence index values, goes through every per-snapshot grid step: H3 cell lookup,
FL bin, evidence update (decay + positive + negative), one advection step and a
full read of p. Timed with perf_counter; p50/p95 over `reps` snapshots. The SPEC
budget is p95 < 2 s for 10k aircraft (the gate fails above it).
"""

from __future__ import annotations

import argparse
import time

import numpy as np

from horus import config
from horus.core import geo, grid
from horus.eval import passes
from horus.reports import replace_section

BUDGET_S = 2.0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--aircraft", type=int, default=10_000)
    ap.add_argument("--reps", type=int, default=50)
    a = ap.parse_args()
    cfg = config.load()
    g, r = cfg.grid, cfg.region
    ids = grid.region_cells(r.lat_min, r.lat_max, r.lon_min, r.lon_max, g.h3_res)
    t_build = time.perf_counter()
    lat_c = grid.Lattice.build(ids)
    t_build = time.perf_counter() - t_build
    n_fl = (g.fl_max - g.fl_min) // g.fl_bin
    p = grid.GridParams(
        l0=-5.0, half_life_s=np.full(n_fl, g.half_life_s), a=1e6, l_pos_max=4.0, tau=1.0, l_neg=2.0
    )
    st = grid.GridState.empty(len(ids), n_fl, p.l0, 0.0)
    rng = np.random.default_rng(0)
    u = rng.normal(30, 15, (len(ids), n_fl))
    v = rng.normal(0, 10, (len(ids), n_fl))
    steps: dict[str, list[float]] = {k: [] for k in ["cells", "update", "advect", "read", "total"]}
    for k in range(a.reps):
        n = a.aircraft
        lat = rng.uniform(r.lat_min, r.lat_max, n)
        lon = rng.uniform(r.lon_min, r.lon_max, n)
        alt = rng.uniform(g.fl_min * 100, g.fl_max * 100 - 1, n)
        T = rng.gamma(1.0, 0.3, n)
        now = 60.0 * (k + 1)
        t0 = time.perf_counter()
        c = grid.cell_index(passes.cell_ids(lat, lon, g.h3_res), ids)
        f = geo.fl_bin(alt, g.fl_min, g.fl_max, g.fl_bin)
        t1 = time.perf_counter()
        grid.update(st, c, f, T, np.ones(n), now, p, T < 0.5)
        t2 = time.perf_counter()
        grid.advect(st, lat_c, u, v, 60.0, now, p)
        t3 = time.perf_counter()
        grid.read(st, now, p)
        t4 = time.perf_counter()
        for key, dt in zip(steps, [t1 - t0, t2 - t1, t3 - t2, t4 - t3, t4 - t0], strict=True):
            steps[key].append(dt)
    rows = {k: (float(np.median(v)), float(np.quantile(v, 0.95))) for k, v in steps.items()}
    ok = rows["total"][1] < BUDGET_S
    lines = [
        f"Generated by `python -m horus.eval.perf_bench --aircraft {a.aircraft} --reps {a.reps}` "
        f"on this laptop (Apple M1, 8 GB). Grid: {len(ids):,} H3 res-{g.h3_res} cells × {n_fl} "
        "FL bins "
        f"({len(ids) * n_fl:,} cells); lattice build (once at start-up) {t_build:.2f} s.",
        "",
        "| Step | p50 (ms) | p95 (ms) |",
        "|---|---|---|",
        *[f"| {k} | {v[0] * 1e3:.1f} | {v[1] * 1e3:.1f} |" for k, v in rows.items()],
        "",
        f"Budget (SPEC §6.4): p95 of one full grid update for {a.aircraft:,} aircraft < "
        f"{BUDGET_S:g} s → "
        f"**{'PASS' if ok else 'FAIL'}** ({rows['total'][1]:.3f} s).",
    ]
    replace_section("perf.md", "grid-update", "\n".join(lines))
    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
